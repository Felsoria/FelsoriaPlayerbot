START TRANSACTION;

INSERT INTO realmlist
    (id, name, address, localAddress, localSubnetMask, port, icon, flag, timezone,
     allowedSecurityLevel, gamebuild, Region, Battlegroup)
SELECT seed.realm_id, seed.realm_name, physical.address, physical.localAddress,
       physical.localSubnetMask, physical.port, seed.icon, 2, seed.client_category,
       physical.allowedSecurityLevel, physical.gamebuild, physical.Region, physical.Battlegroup
FROM realmlist AS physical
CROSS JOIN felsoria_default_realm_catalog AS seed
WHERE physical.id = 1
  AND NOT EXISTS (SELECT 1 FROM realmlist AS existing WHERE existing.id = seed.realm_id)
  AND NOT EXISTS (SELECT 1 FROM realmlist AS existing WHERE existing.name = seed.realm_name);

INSERT INTO felsoria_eu_legion_catalog
    (realm_id, realm_name, language, client_category, enabled, visible)
SELECT seed.realm_id, seed.realm_name, seed.language, seed.client_category, seed.enabled, seed.visible
FROM felsoria_default_realm_catalog AS seed
JOIN realmlist AS realm_row ON realm_row.id = seed.realm_id
    AND realm_row.name = seed.realm_name AND realm_row.timezone = seed.client_category
WHERE NOT EXISTS (SELECT 1 FROM felsoria_eu_legion_catalog AS existing WHERE existing.realm_id = seed.realm_id);

INSERT INTO felsoria_realm_schema (id, version)
SELECT 1, 1
WHERE NOT EXISTS (SELECT 1 FROM felsoria_realm_schema WHERE id = 1);

COMMIT;
